export const getDailyQuote = (scene: string, timePeriod: TimePeriod): string => {
  const sceneData = DAILY_QUOTES_DATABASE[scene] || DAILY_QUOTES_DATABASE.farm;
  const quotesList = sceneData[timePeriod] || sceneData.morning;
  const randomIndex = Math.floor(Math.random() * quotesList.length);
  return quotesList[randomIndex];
};
